/**
 * Intelligent Lyric Auto-Pacer Fallback
 * Returns high-craft time-synced lyrics for native tracks, or generates an ambient,
 * evenly-paced poetic lyric map for local/imported tracks.
 */
export const getTrackLyrics = (track: Track): LyricLine[] => {
  if (track.lyrics && track.lyrics.length > 0) {
    return track.lyrics.map((l) => ({
      ...l,
      time: l.time ?? (l.timeMs ? l.timeMs / 1000 : 0),
    }));
  }

  const dur = Math.max(30, track.duration || 180);
  return [
    { time: Math.round(dur * 0.05), text: `Listening to ${track.title}` },
    { time: Math.round(dur * 0.14), text: `Atmospheric acoustic vibrations by ${track.artistName}` },
    { time: Math.round(dur * 0.25), text: 'Drifting into the resonance of the room' },
    { time: Math.round(dur * 0.38), text: 'Harmonic frequencies fill the open space' },
    { time: Math.round(dur * 0.50), text: 'Every transient pulse aligning with the rhythm' },
    { time: Math.round(dur * 0.64), text: 'Analog warmth flowing through the master output' },
    { time: Math.round(dur * 0.77), text: 'Lost inside the infinite depth of sound' },
    { time: Math.round(dur * 0.88), text: 'Electric echoes slowly dissolving away' },
    { time: Math.round(dur * 0.95), text: 'Pure tranquility remains' },
  ];
};
